# ============================================================
# WHY PydanticOutputParser IS MORE POWERFUL
# ============================================================
#
# JsonOutputParser:
#     Mainly parses valid JSON.
#
# StructuredOutputParser:
#     Defines expected fields/structure.
#
# PydanticOutputParser:
#     Defines structure + types + validation rules.
#
# Example:
#
# age: int = Field(gt=18)
#
# means:
#
#     age must be an integer
#     AND
#     age must be greater than 18
#
# So the flow is:
#
# LLM
#   ↓
# JSON response
#   ↓
# PydanticOutputParser
#   ↓
# Parse + Validate
#   ↓
# Person object